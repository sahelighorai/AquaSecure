def snapshot_csv(snap: dict) -> str:
    buf = io.StringIO()
    writer = csv.writer(buf)
    writer.writerow(list(snap.keys()))
    writer.writerow(list(snap.values()))
    return buf.getvalue()


def snapshot_json(snap: dict) -> str:
    return json.dumps(snap, indent=2, default=str)


def snapshot_latex_row(snap: dict) -> str:
    def g(k):
        v = snap[k]
        return v
    lmax = "—" if snap["max_secure_distance_m"] is None else f"{snap['max_secure_distance_m']:.2f}"
    return (
        f"{snap['water_type']} & {snap['distance_m']:.1f} & {snap['ntu']:.0f} & "
        f"{snap['background'].split(' ')[0]} & {100*snap['detector_efficiency']:.0f}\\% & "
        f"{snap['attenuation_c_m^-1']:.2f} & {snap['channel_loss_db']:.1f} & "
        f"{snap['qber_percent']:.2f} & {snap['secure_rate_bps']/1e3:.2f} & "
        f"{snap['security_status']} & {lmax} \\\\"
    )


